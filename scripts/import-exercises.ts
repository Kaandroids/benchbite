// Imports the free-exercise-db exercise library at a pinned commit: it writes a migration that
// inserts or updates every exercise with its metrics, the translated names from
// supabase/data/exercise-names.json and the steps from supabase/data/exercise-instructions.*.json.
//
// Two things of the library are not taken. Its pictures: the rights to them are not known, and
// the app shows a muscle map in their place (ADR 0162, ADR 0163). Its steps: they are written in
// the project's own words, in English, German and Turkish (ADR 0164).
//
// Run with `pnpm import:exercises`. To update the library, change UPSTREAM_COMMIT, write the steps
// of any new exercise, run the script again and commit the new migration.
//
// `pnpm import:exercises --names-only` writes a small migration with only the translated names,
// for when exercise-names.json changes but the library does not, and
// `pnpm import:exercises --instructions-only` one with only the steps.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import type { Database } from '../src/lib/database.types.ts';
import { MIGRATIONS_DIR, sqlString, timestamp } from './lib/migration.ts';

const UPSTREAM_COMMIT = 'f00c92c7dcf1216a928a52c3706c7ce8e2f71ed5';
const UPSTREAM = `https://raw.githubusercontent.com/yuhonas/free-exercise-db/${UPSTREAM_COMMIT}`;

const ROOT = join(import.meta.dirname, '..');
const NAMES_FILE = join(ROOT, 'supabase', 'data', 'exercise-names.json');
const METRICS_FILE = join(ROOT, 'supabase', 'data', 'exercise-metrics.json');
/** The steps of every exercise by its id, one file for each language. */
const INSTRUCTION_LANGUAGES = ['en', 'de', 'tr'] as const;
const instructionsFile = (language: string) =>
  join(ROOT, 'supabase', 'data', `exercise-instructions.${language}.json`);

type UpstreamExercise = {
  id: string;
  name: string;
  level: string;
  category: string;
  equipment: string | null;
  force: string | null;
  mechanic: string | null;
  primaryMuscles: string[];
  secondaryMuscles: string[];
};

type TranslatedNames = Record<string, { de: string; tr: string }>;

/** The steps of each exercise, by its id. */
type Steps = Record<string, string[]>;
type Instructions = Record<(typeof INSTRUCTION_LANGUAGES)[number], Steps>;

type Metric = Database['public']['Enums']['exercise_metric'];

/** Equipment that adds no weight to measure. */
const UNWEIGHTED_EQUIPMENT = new Set([null, 'body only', 'bands', 'exercise ball']);

/**
 * The metrics most exercises of a kind record. Exceptions are listed in
 * supabase/data/exercise-metrics.json.
 */
function defaultMetrics(exercise: UpstreamExercise): Metric[] {
  if (exercise.category === 'stretching' || exercise.equipment === 'foam roll') {
    return ['duration'];
  }
  if (exercise.category === 'cardio') {
    return ['distance', 'duration'];
  }
  // Holds such as planks and isometric exercises.
  if (exercise.force === 'static') {
    return ['duration'];
  }
  // Jumps and bounds on boxes, hurdles and cones are counted, not weighed.
  if (
    UNWEIGHTED_EQUIPMENT.has(exercise.equipment) ||
    (exercise.category === 'plyometrics' && exercise.equipment === 'other')
  ) {
    return ['reps'];
  }
  return ['weight', 'reps'];
}

async function fetchExercises(): Promise<UpstreamExercise[]> {
  const response = await fetch(`${UPSTREAM}/dist/exercises.json`);
  if (!response.ok) {
    throw new Error(`Could not download the exercises: ${response.status}`);
  }
  return (await response.json()) as UpstreamExercise[];
}

function sqlArray(values: string[], type: string): string {
  return `array[${values.map(sqlString).join(', ')}]::${type}[]`;
}

function exerciseRow(exercise: UpstreamExercise, metrics: Metric[], steps: string[]): string {
  return `  (${[
    sqlString(exercise.id),
    sqlString(exercise.name),
    sqlString(exercise.level),
    sqlString(exercise.category),
    sqlString(exercise.equipment),
    sqlString(exercise.force),
    sqlString(exercise.mechanic),
    sqlArray(exercise.primaryMuscles, 'public.muscle'),
    sqlArray(exercise.secondaryMuscles, 'public.muscle'),
    sqlArray(steps, 'text'),
    // No pictures: the column is for the photos of the users' own exercises.
    sqlArray([], 'text'),
    sqlArray(metrics, 'public.exercise_metric'),
  ].join(', ')})`;
}

const HEADER = `-- Generated by scripts/import-exercises.ts from free-exercise-db at commit
-- ${UPSTREAM_COMMIT}. Do not edit by hand.
`;

const HEADER_OWN = `-- Generated by scripts/import-exercises.ts from supabase/data/exercise-instructions.*.json,
-- the steps of the library's exercises in the project's own words (ADR 0164). Do not edit by hand.
`;

function exercisesSql(
  exercises: UpstreamExercise[],
  metricOverrides: Record<string, Metric[]>,
  steps: Steps,
): string {
  return `
insert into public.exercises (
  id, name, level, category, equipment, force, mechanic,
  primary_muscles, secondary_muscles, instructions, image_paths, metrics
)
values
${exercises
  .map((exercise) =>
    exerciseRow(
      exercise,
      metricOverrides[exercise.id] ?? defaultMetrics(exercise),
      steps[exercise.id] ?? [],
    ),
  )
  .join(',\n')}
on conflict (id) do update set
  name = excluded.name,
  level = excluded.level,
  category = excluded.category,
  equipment = excluded.equipment,
  force = excluded.force,
  mechanic = excluded.mechanic,
  primary_muscles = excluded.primary_muscles,
  secondary_muscles = excluded.secondary_muscles,
  instructions = excluded.instructions,
  image_paths = excluded.image_paths,
  metrics = excluded.metrics;
`;
}

function translationsSql(names: TranslatedNames): string {
  const translations = Object.entries(names).flatMap(([id, byLanguage]) =>
    Object.entries(byLanguage).map(
      ([language, name]) => `  (${[id, language, name].map(sqlString).join(', ')})`,
    ),
  );
  return `
insert into public.exercise_translations (exercise_id, language, name)
values
${translations.join(',\n')}
on conflict (exercise_id, language) do update set name = excluded.name;
`;
}

/** The English steps of the library's exercises, for a migration that changes nothing else. */
function englishInstructionsSql(steps: Steps): string {
  return `
update public.exercises as exercise
set instructions = steps.instructions
from (
  values
${Object.entries(steps)
  .map(([id, list]) => `    (${sqlString(id)}, ${sqlArray(list, 'text')})`)
  .join(',\n')}
) as steps (id, instructions)
where exercise.id = steps.id
  and exercise.owner_id is null;
`;
}

function instructionTranslationsSql(instructions: Instructions): string {
  const rows = (['de', 'tr'] as const).flatMap((language) =>
    Object.entries(instructions[language]).map(
      ([id, list]) => `  (${sqlString(id)}, ${sqlString(language)}, ${sqlArray(list, 'text')})`,
    ),
  );
  return `
insert into public.exercise_instruction_translations (exercise_id, language, instructions)
values
${rows.join(',\n')}
on conflict (exercise_id, language) do update set instructions = excluded.instructions;
`;
}

const exercises = (await fetchExercises()).sort((a, b) => a.id.localeCompare(b.id));
const names = JSON.parse(readFileSync(NAMES_FILE, 'utf8')) as TranslatedNames;

const metricOverrides = JSON.parse(readFileSync(METRICS_FILE, 'utf8')) as Record<string, Metric[]>;

const instructions = Object.fromEntries(
  INSTRUCTION_LANGUAGES.map((language) => [
    language,
    JSON.parse(readFileSync(instructionsFile(language), 'utf8')) as Steps,
  ]),
) as Instructions;

const ids = new Set(exercises.map((exercise) => exercise.id));
for (const [file, entries] of [
  ['exercise-names.json', names],
  ['exercise-metrics.json', metricOverrides],
  ...INSTRUCTION_LANGUAGES.map(
    (language) => [`exercise-instructions.${language}.json`, instructions[language]] as const,
  ),
] as const) {
  const unknown = Object.keys(entries).filter((id) => !ids.has(id));
  if (unknown.length > 0) {
    throw new Error(`${file} has unknown exercises: ${unknown.join(', ')}`);
  }
}

// Every exercise has its steps in every language, as many in each as in English: the app shows
// one language's steps in place of another's.
for (const exercise of exercises) {
  const counts = INSTRUCTION_LANGUAGES.map(
    (language) => instructions[language][exercise.id]?.length,
  );
  if (counts.some((count) => count === undefined || count === 0 || count !== counts[0])) {
    throw new Error(
      `${exercise.id} needs the same number of steps in ${INSTRUCTION_LANGUAGES.join(', ')}: ` +
        counts.map((count) => count ?? 'none').join(', '),
    );
  }
}

if (process.argv.includes('--instructions-only')) {
  const file = join(MIGRATIONS_DIR, `${timestamp()}_import_exercise_instructions.sql`);
  writeFileSync(
    file,
    HEADER_OWN + englishInstructionsSql(instructions.en) + instructionTranslationsSql(instructions),
  );
  console.log(`Wrote the steps of ${exercises.length} exercises to ${file}`);
} else if (process.argv.includes('--names-only')) {
  const file = join(MIGRATIONS_DIR, `${timestamp()}_import_exercise_names.sql`);
  writeFileSync(file, HEADER + translationsSql(names));
  console.log(`Wrote ${Object.keys(names).length} names to ${file}`);
} else {
  const file = join(MIGRATIONS_DIR, `${timestamp()}_import_exercises.sql`);
  writeFileSync(
    file,
    HEADER +
      exercisesSql(exercises, metricOverrides, instructions.en) +
      translationsSql(names) +
      instructionTranslationsSql(instructions),
  );
  console.log(
    `Wrote ${exercises.length} exercises and ${Object.keys(names).length} names to ${file}`,
  );
}
